<?php
/**
 * Render a single Morsel (Tidbit post) on the front end.
 *
 * @param array    $attributes The block attributes.
 * @param string   $content    Not used (dynamic block).
 * @param WP_Block $block      The block instance.
 *
 * @package Tidbits
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$tidbits_post_id = $attributes['postId'] ?? 0;

if ( ! $tidbits_post_id ) {
	return;
}

$tidbits_post = get_post( $tidbits_post_id );

if ( ! $tidbits_post || 'tidbit' !== $tidbits_post->post_type || 'publish' !== $tidbits_post->post_status ) {
	return;
}

$tidbits_display_mode = $block->context['tidbits/displayMode'] ?? 'accordion';
$tidbits_title        = esc_html( get_the_title( $tidbits_post ) );

// Collect CSS custom properties passed down from the parent Tidbits block.
$tidbits_morsel_props   = [];
$tidbits_divider_border = $block->context['tidbits/dividerBorder'] ?? [];
$tidbits_item_padding   = $block->context['tidbits/itemPadding'] ?? '';

if ( ! empty( $tidbits_divider_border['color'] ) ) {
	$tidbits_morsel_props[] = '--tidbits-divider-color: ' . esc_attr( $tidbits_divider_border['color'] );
}
if ( ! empty( $tidbits_divider_border['width'] ) ) {
	$tidbits_morsel_props[] = '--tidbits-divider-width: ' . esc_attr( $tidbits_divider_border['width'] );
}
if ( ! empty( $tidbits_divider_border['style'] ) && 'none' !== $tidbits_divider_border['style'] ) {
	$tidbits_morsel_props[] = '--tidbits-divider-style: ' . esc_attr( $tidbits_divider_border['style'] );
}
if ( '' !== $tidbits_item_padding ) {
	// Resolve a spacing preset reference (var:preset|spacing|40) to its CSS
	// custom property; any other value (e.g. '0') passes through unchanged.
	if ( 0 === strpos( $tidbits_item_padding, 'var:preset|spacing|' ) ) {
		$tidbits_padding_slug  = substr( $tidbits_item_padding, strlen( 'var:preset|spacing|' ) );
		$tidbits_padding_value = sprintf( 'var(--wp--preset--spacing--%s)', $tidbits_padding_slug );
	} else {
		$tidbits_padding_value = $tidbits_item_padding;
	}
	$tidbits_morsel_props[] = '--tidbits-padding-block: ' . esc_attr( $tidbits_padding_value );
}
$tidbits_morsel_style = ! empty( $tidbits_morsel_props ) ? implode( '; ', $tidbits_morsel_props ) : '';
// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Core filter required to render block content.
$tidbits_content = apply_filters( 'the_content', $tidbits_post->post_content );

if ( 'accordion' === $tidbits_display_mode ) :
	// Unique IDs so the same Tidbit used across multiple blocks on one page
	// can't produce duplicate IDs that would break the ARIA associations.
	$tidbits_toggle_id    = wp_unique_id( 'tidbits-toggle-' );
	$tidbits_panel_id     = $tidbits_toggle_id . '-panel';
	$tidbits_context      = wp_interactivity_data_wp_context( array( 'isOpen' => false ) );
	$tidbits_morsel_args = array( 'class' => 'tidbits-morsel tidbits-morsel--accordion' );
	if ( $tidbits_morsel_style ) {
		$tidbits_morsel_args['style'] = $tidbits_morsel_style;
	}
	$tidbits_wrapper_attrs = get_block_wrapper_attributes( $tidbits_morsel_args );
	?>
	<div <?php echo $tidbits_wrapper_attrs; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes. ?> <?php echo $tidbits_context; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_interactivity_data_wp_context. ?>>
		<h3 class="tidbits-morsel__heading">
			<button
				type="button"
				class="tidbits-morsel__trigger"
				id="<?php echo esc_attr( $tidbits_toggle_id ); ?>"
				aria-controls="<?php echo esc_attr( $tidbits_panel_id ); ?>"
				aria-expanded="false"
				data-wp-on--click="actions.toggle"
				data-wp-bind--aria-expanded="context.isOpen"
			>
				<?php // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Already escaped with esc_html above. ?>
				<span class="tidbits-morsel__title"><?php echo $tidbits_title; ?></span>
				<svg
					class="tidbits-morsel__icon"
					data-wp-class--is-open="context.isOpen"
					xmlns="http://www.w3.org/2000/svg"
					width="20"
					height="20"
					viewBox="0 0 24 24"
					fill="none"
					stroke="currentColor"
					stroke-width="2"
					stroke-linecap="round"
					stroke-linejoin="round"
					aria-hidden="true"
				>
					<polyline points="9 18 15 12 9 6"></polyline>
				</svg>
			</button>
		</h3>
		<div
			class="tidbits-morsel__panel"
			id="<?php echo esc_attr( $tidbits_panel_id ); ?>"
			aria-labelledby="<?php echo esc_attr( $tidbits_toggle_id ); ?>"
			inert
			data-wp-bind--inert="!context.isOpen"
			data-wp-class--is-open="context.isOpen"
		>
			<div class="tidbits-morsel__inner">
				<?php echo wp_kses_post( $tidbits_content ); ?>
			</div>
		</div>
	</div>
	<?php
else :
	$tidbits_mode_class    = 'columns' === $tidbits_display_mode ? 'tidbits-morsel--columns' : 'tidbits-morsel--stacked';
	$tidbits_morsel_args = array( 'class' => 'tidbits-morsel ' . $tidbits_mode_class );
	if ( $tidbits_morsel_style ) {
		$tidbits_morsel_args['style'] = $tidbits_morsel_style;
	}
	$tidbits_wrapper_attrs = get_block_wrapper_attributes( $tidbits_morsel_args );
	?>
	<div <?php echo $tidbits_wrapper_attrs; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes. ?>>
		<?php // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Already escaped with esc_html above. ?>
		<dt class="tidbits-morsel__term"><?php echo $tidbits_title; ?></dt>
		<dd class="tidbits-morsel__content">
			<?php echo wp_kses_post( $tidbits_content ); ?>
		</dd>
	</div>
	<?php
endif;
